import assert from 'node:assert/strict';
import { CATALOG, validateItems, containsItems, matchListings } from '../lib/plaza-model.mjs';
const item = (pet = 'turtle', quantity = 1, extra = {}) => ({ pet, variant: 'normal', fly: false, ride: false, quantity, ...extra });
assert.equal(CATALOG.length, 801);
assert.deepEqual(validateItems([item()]), [item()]);
assert.deepEqual(validateItems([], { allowEmpty: true }), []);
for (const invalid of [[], null, {}, [item('fake')], [item('turtle', 0)], [item('turtle', 19)], [item('turtle', 1.5)], [item('turtle', '1')], [item('turtle', 1, { variant: 'rare' })], [item('turtle', 1, { fly: 1 })], [item(), item()], [item('egg', 1, { variant: 'neon' })], [item('ride-potion', 1, { ride: true })], [item('fly-potion', 1, { fly: true })], [item('cow', 10), item('owl', 9)]]) assert.throws(() => validateItems(invalid));
assert.equal(validateItems(CATALOG.slice(0, 6).map(p => item(p.id, 3))).length, 6);
assert.throws(() => validateItems(CATALOG.slice(0, 7).map(p => item(p.id))));
assert.equal(containsItems([item('cow', 2)], [item('cow', 2)]), true);
assert.equal(containsItems([item('cow', 1)], [item('cow', 2)]), false);
assert.equal(containsItems([item('cow', 2, { fly: true })], [item('cow', 1)]), false);
assert.equal(containsItems([item('cow', 2, { variant: 'neon' })], [item('cow', 1)]), false);
const now = 1000;
const listing = (id, owner, have, want, extra = {}) => ({ id, owner_id: owner, have, want, status: 'active', created_at: 1, expires_at: 2000, ready_until: 0, ...extra });
const source = listing('mine', 'alice', [item('turtle', 2)], [item('cow')]);
const yes = listing('yes', 'bob', [item('cow')], [item('turtle', 2)]);
const quantityNo = listing('quantity-no', 'bob', [item('cow')], [item('turtle', 3)]);
const flagNo = listing('flag-no', 'bob', [item('cow', 1, { fly: true })], [item('turtle')]);
const open = listing('open', 'chris', [item('cow')], []);
const expired = listing('expired', 'dave', [item('cow')], [item('turtle')], { expires_at: 999 });
const same = listing('same', 'alice', [item('cow')], [item('turtle')]);
assert.deepEqual(matchListings(source, [quantityNo, flagNo, expired, same, source, yes, open], now).map(x => [x.listing.id, x.kind]), [['yes', 'mutual'], ['open', 'open']]);
assert.equal(matchListings({ ...source, status: 'reserved' }, [yes], now).length, 0);
assert.equal(matchListings({ ...source, expires_at: 1000 }, [yes], now).length, 0);
assert.equal(matchListings(source, [{ ...open, ready_until: 1500 }, yes], now)[0].listing.id, 'open');
assert.equal(matchListings({ ...source, want: [] }, [yes], now)[0].kind, 'open');
console.log('PASS plaza model: catalogue, exact variants/flags, quantities, bundle limits, duplicate rejection, reciprocal/open matching, expiry and readiness.');
